#!/usr/bin/env node
// Genera, a partir de shared/actions.json y shared/ring-layout.json:
//   - logi-plugin/src/Actions/Commands.g.cs           (una clase C# por acción)
//   - logi-plugin/src/package/actionsymbols/*.svg     (iconos del selector de acciones)
//   - logi-plugin/src/package/icontemplates/*.ict     (iconos de las burbujas del Actions Ring)
//   - logi-plugin/src/package/events/...yaml          (eventos hápticos del MX Master 4)
//   - profiles/ClaudeCode-ActionsRing-{es,en}.lp5     (perfil del Actions Ring, experimental)
// Uso: node scripts/generate.mjs          -> escribe los archivos
//      node scripts/generate.mjs --check  -> falla si algo generado está desactualizado (CI)
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";
import { iconSvg } from "./icons.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const PLUGIN_NAME = "ClaudeCode";
const NAMESPACE = "Loupedeck.ClaudeCodePlugin";

const catalog = JSON.parse(fs.readFileSync(path.join(root, "shared/actions.json"), "utf8"));
const ring = JSON.parse(fs.readFileSync(path.join(root, "shared/ring-layout.json"), "utf8"));
const en = JSON.parse(fs.readFileSync(path.join(root, "shared/i18n.en.json"), "utf8"));
const byId = new Map(catalog.actions.map((a) => [a.id, a]));

// "#RRGGBB" -> ARGB opaco (formato de color de los .ict)
const argb = (hex) => (0xff000000 | parseInt(hex.replace("#", ""), 16)) >>> 0;
const RING_BACKGROUND = argb(ring.iconColors?.background ?? "#D8D8D8");
const ICON_COLOR = argb(ring.iconColors?.foreground ?? "#000000");

const outputs = new Map(); // ruta relativa -> Buffer
const put = (rel, content) => outputs.set(rel, Buffer.isBuffer(content) ? content : Buffer.from(content, "utf8"));

// ---------- C# ----------
{
  const lines = [
    "// <auto-generated>",
    "// Generado por scripts/generate.mjs a partir de shared/actions.json. No editar a mano.",
    "// </auto-generated>",
    `namespace ${NAMESPACE};`,
    "",
  ];
  for (const a of catalog.actions) {
    lines.push(`/// <summary>${a.displayName}: ${a.description.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")}</summary>`);
    lines.push(`public sealed class ${a.className} : ClaudeCommandBase`);
    lines.push("{");
    lines.push(`    public ${a.className}() : base("${a.id}") { }`);
    lines.push("}");
    lines.push("");
  }
  put("logi-plugin/src/Actions/Commands.g.cs", lines.join("\n"));
}

// ---------- Iconos ----------
const ict = (svg, fileName) =>
  JSON.stringify(
    {
      backgroundColor: RING_BACKGROUND,
      items: [
        {
          $type: "Loupedeck.Service.ActionIconImageItem, LoupedeckShared",
          image: Buffer.from(svg).toString("base64"),
          imageFileName: fileName,
          imageColor: ICON_COLOR,
          imageRotation: "None",
          isVisible: true,
          itemType: "Image",
          area: { x: 25, y: 25, width: 50, height: 50, isFullScreen: false },
        },
      ],
    },
    null,
    2,
  ) + "\n";

for (const a of catalog.actions) {
  const full = `${NAMESPACE}.${a.className}`;
  const svg = iconSvg(a.icon);
  put(`logi-plugin/src/package/actionsymbols/${full}.svg`, svg);
  put(`logi-plugin/src/package/icontemplates/${full}.ict`, ict(svg, `${full}.svg`));
}

// ---------- Eventos hápticos ----------
{
  const src = [
    "# Generado por scripts/generate.mjs. No editar a mano.",
    "displayName: Claude Code",
    "description: MX Master 4 haptic feedback for Claude Code Desktop actions",
    "events:",
  ];
  const map = ["# Generado por scripts/generate.mjs. No editar a mano.", "haptics:"];
  for (const [name, h] of Object.entries(catalog.haptics)) {
    const t = en.haptics[name];
    src.push(`    - name: ${name}`, `      displayName: ${JSON.stringify(t.displayName)}`, `      description: ${JSON.stringify(t.description)}`);
    map.push(`    ${name}:`, `        DEFAULT: ${h.waveform}`);
  }
  put("logi-plugin/src/package/events/DefaultEventSource.yaml", src.join("\n") + "\n");
  put("logi-plugin/src/package/events/extra/eventMapping.yaml", map.join("\n") + "\n");
}

// ---------- Perfil del Actions Ring (.lp5) ----------
const guid = (seed) => crypto.createHash("sha1").update(`claude-mx:${seed}`).digest("hex").slice(0, 32).toUpperCase();
const actionName = (id) => {
  const a = byId.get(id);
  if (!a) throw new Error(`ring-layout.json usa una acción inexistente: ${id}`);
  return `$${PLUGIN_NAME}___${NAMESPACE}.${a.className}`;
};
const control = (controlId, pressAction) => ({
  $type: "Loupedeck.Service.Devices.Loupedeck7Devices.ProfileLayoutControl7, LoupedeckService",
  controlId,
  pressAction,
  rotateAction: null,
});
const page = (name, displayName, controls) => ({
  $type: "Loupedeck.Service.Devices.Loupedeck7Devices.ProfileLayoutPage7, LoupedeckService",
  name,
  displayName,
  description: "",
  controls,
});

function buildProfile(lang) {
  const L = (es, eng) => (lang === "en" ? eng : es);
  const actionText = (id) => ({
    displayName: L(byId.get(id).displayName, en.actions[id].displayName),
    description: L(byId.get(id).description, en.actions[id].description),
  });
  if (ring.slots.length > 8) throw new Error("El Actions Ring admite como máximo 8 burbujas");
  const profileId = guid(`profile:${lang}`);
  const folderPages = [];
  const profileActions = [];
  const actionIcons = {};
  const preview = [];
  const mainControls = [];

  ring.slots.forEach((slot, i) => {
    if (typeof slot === "string") {
      const name = actionName(slot);
      mainControls.push(control(i, name));
      preview.push({ controlId: i, actionName: name, ...actionText(slot), image: null });
      return;
    }
    const folderName = L(slot.folder, slot.folderEn ?? slot.folder);
    const folderId = guid(`folder:${lang}:${slot.folder}`);
    const folderAction = `$@Generic___@ProfileAction___${folderId}`;
    if (slot.actions.length > 9) throw new Error(`La carpeta ${folderName} tiene más de 9 acciones`);
    folderPages.push(page(folderId, "Folder", slot.actions.map((id, j) => control(j, actionName(id)))));
    profileActions.push({
      $type: "Loupedeck.Service.ApplicationProfileCommand, LoupedeckService",
      isCommand: true,
      name: folderAction,
      templateActionName: "$@Generic___@OpenFolder",
      actionParameters: {
        $type: "Loupedeck.ActionEditorActionParameters, PluginApi",
        parameters: { $type: "Loupedeck.StringDictionaryNoCase, PluginApi", folderName: folderId },
        count: 1,
      },
      displayName: folderName,
      description: "",
      groupName: "Folders",
      superGroupName: "@navigation",
      isProfileAction: true,
      isMultiState: false,
      isResetCommand: false,
      adjustmentName: null,
      states: null,
    });
    actionIcons[`ActionIcons/${folderAction}.ict`] = ict(iconSvg(slot.icon), `${folderName}.svg`);
    mainControls.push(control(i, folderAction));
    preview.push({ controlId: i, actionName: folderAction, displayName: folderName, description: "", image: null });
  });
  for (let i = ring.slots.length; i < 8; i++) mainControls.push(control(i, null));

  const profileInfo = {
    $type: "Loupedeck.Service.ApplicationProfile, LoupedeckService",
    name: profileId,
    profileFlags: "None",
    displayName: L(ring.profileName, ring.profileNameEn ?? ring.profileName),
    description: L("Atajos de Claude Code Desktop para el Actions Ring del MX Master 4", "Claude Code Desktop shortcuts for the MX Master 4 Actions Ring"),
    deviceType: "Loupedeck72",
    applicationName: `@_${PLUGIN_NAME.toLowerCase()}`,
    nativePluginName: PLUGIN_NAME,
    hasNativePlugin: true,
    additionalNativePluginNames: [],
    lastModifiedTimeUtc: "2026-11-04T00:00:00Z",
    profileSettings: { $type: "Loupedeck.DictionaryNoCase`1[[System.String, System.Private.CoreLib]], PluginApi" },
    actionImages90: null,
    actionImages60: null,
    wheelImages: null,
    actionColors: null,
    layout: {
      $type: "Loupedeck.Service.Devices.Loupedeck7Devices.ProfileLayout7, LoupedeckService",
      deviceType: "Loupedeck72",
      profileFlags: "None",
      layoutModes: [
        {
          $type: "Loupedeck.Service.Devices.Loupedeck7Devices.ProfileLayoutMode7, LoupedeckService",
          deviceType: "Loupedeck72",
          modeName: "main",
          parentModeName: null,
          actions: null,
          dynamicButtonPages: null,
          dynamicEncoderPages: null,
          workspaces: [
            {
              $type: "Loupedeck.Service.Devices.Loupedeck7Devices.ProfileLayoutWorkspace7, LoupedeckService",
              name: guid("workspace"),
              displayName: "Workspace 1",
              description: null,
              pressPages: [page(guid("page"), "Page (1)", mainControls)],
              rotatePages: [page(guid("dial"), "Dial Page", [0, 1, 2, 3].map((i) => control(i, null)))],
            },
          ],
          homeWorkspaceName: guid("workspace"),
        },
      ],
      folderPages,
    },
    macroCommands: [],
    macroAdjustments: [],
    profileCommands: [],
    profileAdjustments: [],
    conversionHistory: "",
    packageName: null,
    packageVersion: null,
    profileActions,
  };

  const applicationInfo = {
    $type: "Loupedeck.Service.SupportedApplicationInfo, LoupedeckService",
    name: `@_${PLUGIN_NAME.toLowerCase()}`,
    displayName: "Claude",
    description: null,
    deviceType: "Loupedeck72",
    nativePluginName: PLUGIN_NAME,
    hasNativePlugin: true,
    processOrBundleName: "com.anthropic.claudefordesktop",
    modes: [{ $type: "Loupedeck.Service.ApplicationMode, LoupedeckService", name: "main", parentModeName: null, displayName: "Main" }],
    defaultProfileName: profileId,
    isEnabled: true,
  };

  const json = (o) => JSON.stringify(o, null, 4);
  const files = {
    "metadata/LoupedeckPackage.yaml": `type: Profile5\nname: ${profileId}\ndisplayName: ${L(ring.profileName, ring.profileNameEn ?? ring.profileName)}\nversion: 1.0\n`,
    "metadata/AdvancedInfo.json": json({ additionalPluginNames: [PLUGIN_NAME] }),
    "metadata/ProfilePreview.json": json({ buttonPages: preview, encoderPages: [null, null, null, null] }),
    "ApplicationInfo.json": json(applicationInfo),
    "ProfileInfo.json": json(profileInfo),
    ...actionIcons,
  };
  for (const a of new Set(ring.slots.flatMap((s) => (typeof s === "string" ? [s] : s.actions)))) {
    const full = `${NAMESPACE}.${byId.get(a).className}`;
    files[`ActionIcons/${actionName(a)}.ict`] = ict(iconSvg(byId.get(a).icon), `${full}.svg`);
  }
  return zip(files);
}

// Zip mínimo y determinista (deflate + CRC32 de zlib), sin dependencias.
function zip(files) {
  const DOS_TIME = 0;
  const DOS_DATE = ((2026 - 1980) << 9) | (11 << 5) | 4;
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const [name, content] of Object.entries(files).sort(([a], [b]) => a.localeCompare(b))) {
    const data = Buffer.from(content, "utf8");
    const deflated = zlib.deflateRawSync(data, { level: 9 });
    const crc = zlib.crc32(data);
    const nameBuf = Buffer.from(name, "utf8");
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6); // nombres UTF-8
    local.writeUInt16LE(8, 8);
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(deflated.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, nameBuf, deflated);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt16LE(DOS_TIME, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(deflated.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBuf);
    offset += local.length + nameBuf.length + deflated.length;
  }
  const centralBuf = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(Object.keys(files).length, 8);
  end.writeUInt16LE(Object.keys(files).length, 10);
  end.writeUInt32LE(centralBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, centralBuf, end]);
}

put("profiles/ClaudeCode-ActionsRing-es.lp5", buildProfile("es"));
put("profiles/ClaudeCode-ActionsRing-en.lp5", buildProfile("en"));

// ---------- Escribir / comprobar ----------
const generatedDirs = ["logi-plugin/src/package/actionsymbols", "logi-plugin/src/package/icontemplates", "profiles"];
const stale = [];
for (const [rel, content] of outputs) {
  const abs = path.join(root, rel);
  const current = fs.existsSync(abs) ? fs.readFileSync(abs) : null;
  if (current && current.equals(content)) continue;
  if (check) stale.push(rel);
  else {
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
  }
}
for (const dir of generatedDirs) {
  const abs = path.join(root, dir);
  if (!fs.existsSync(abs)) continue;
  for (const f of fs.readdirSync(abs)) {
    const rel = `${dir}/${f}`;
    if (!outputs.has(rel)) {
      if (check) stale.push(`${rel} (sobrante)`);
      else fs.rmSync(path.join(root, rel));
    }
  }
}
if (check && stale.length) {
  console.error("Archivos generados desactualizados. Ejecuta `node scripts/generate.mjs`:\n  " + stale.join("\n  "));
  process.exit(1);
}
console.log(check ? "Archivos generados al día." : `Generados ${outputs.size} archivos.`);
